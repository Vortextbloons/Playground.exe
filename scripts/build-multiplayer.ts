import { access, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { discoverGames } from '../src/data/games';

const games = (await discoverGames()).filter(game => game.multiplayer);
const imports: string[] = [];
const entries: string[] = [];
for (const [index, game] of games.entries()) {
  await access(resolve('games', game.id, 'src/multiplayer.ts')).catch(() => { throw new Error(`${game.id} declares multiplayer but needs src/multiplayer.ts with a default defineMultiplayer export.`); });
  imports.push(`import game${index} from '../../games/${game.id}/src/multiplayer';`);
  entries.push(`${JSON.stringify(game.id)}: { ...${JSON.stringify({ id: game.id, title: game.title, multiplayer: game.multiplayer })}, definition: game${index} }`);
}
await writeFile(resolve('workers/party/registry.generated.ts'), `// Generated by npm run build:multiplayer. Do not edit.\nimport type { Registry } from './engine';\n${imports.join('\n')}\nexport const games: Registry = {\n${entries.join(',\n')}\n};\n`);
console.log(`Registered ${games.length} multiplayer games.`);
